export const getLandDisplayName = (land: string): string => {
  const names: Record<string, string> = {
    main_street: 'Main Street, U.S.A.',
    adventureland: 'Adventureland',
    frontierland: 'Frontierland',
    liberty_square: 'Liberty Square',
    fantasyland: 'Fantasyland',
    tomorrowland: 'Tomorrowland',
  };
  return names[land] || land;
};

export const getWaitTimeColor = (waitTime: number): string => {
  if (waitTime <= 15) return '#34C759';
  if (waitTime <= 30) return '#F2B138';
  if (waitTime <= 60) return '#FF9500';
  return '#FF3B30';
};
